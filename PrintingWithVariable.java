public class PrintingWithVariable {
    static void main() {
        String name = "Daman";
        int age = 22;
        String college = "World college of tech and management";
        Float CGPA = 7.4f;
        System.out.println(name);
        System.out.println(age);
        System.out.println(college);
        System.out.println(CGPA);
    }
}
